import csv
import json
import sys
from pathlib import Path

import library

ROOT = Path(__file__).resolve().parents[1]
DUMPS = ROOT / "tmp" / "params"
SWEEP = ["0", "0.25", "0.5", "0.75", "1"]
SKIP = ("midi cc", "program", "preset", "bank", "patch", "browse", "reserved")


def sweepable(name: str) -> bool:
    n = name.lower()
    return not any(w in n for w in SKIP)


def load_dumps() -> dict:
    out = {}
    for f in sorted(DUMPS.glob("pass1_*.json")):
        for p in json.loads(f.read_text(encoding="utf-8")):
            out[tuple(p["at"])] = p
    return out


def load_sweep() -> dict:
    out = {}
    for v in SWEEP:
        for f in [DUMPS / f"sweep_{v}.json"] + sorted(DUMPS.glob(f"sweep_*_{v}.json")):
            if not f.exists():
                continue
            for at, rows in json.loads(f.read_text(encoding="utf-8")).items():
                key = tuple(int(x) for x in at.split(","))
                for r in rows:
                    out.setdefault(key, {}).setdefault(int(r[0]), {})[v] = (r[1], r[2], r[3] if len(r) > 3 else None)
    return out


def where(e: dict) -> tuple:
    return (e["channel"], -1) if e["kind"] == "instrument" else (e["track"], e["slot"])


def cell(v: str, got, name: str) -> str:
    if got is None:
        return ""
    val, disp, now = got
    disp = (disp or "").strip()
    if now is not None and now != name:
        disp += f" [renamed {now}]"
    if abs(float(val) - float(v)) > 0.01:
        disp += f" [landed {float(val):.3f}]"
    return disp


def write() -> list[dict]:
    dumps, sweep = load_dumps(), load_sweep()
    library.PARAMS.mkdir(parents=True, exist_ok=True)
    index = []
    for e in library.entries():
        p = dumps.get(where(e))
        if p is None:
            index.append({**e, "rows": None})
            continue
        sw = sweep.get(where(e), {})
        cols = ["index", "name", "value", "display"] + ([f"at {v}" for v in SWEEP] if sw else [])
        with library.param_file(e).open("w", encoding="utf-8", newline="") as fh:
            w = csv.writer(fh, delimiter="\t", lineterminator="\n")
            w.writerow(cols)
            for i, name, val, disp in p["rows"]:
                row = [i, name, f"{float(val):.4f}", (disp or "").strip()]
                if sw:
                    row += [cell(v, sw.get(int(i), {}).get(v), name) for v in SWEEP]
                w.writerow(row)
        index.append({**e, "rows": len(p["rows"]), "count": p["count"], "live": p["plugin"], "swept": bool(sw)})
    lines = ["# Parameter maps", "",
             "Generated by `scripts/parammap.py` from live reads of the library project (config key `library`); never hand-edit, regenerate. One TSV per plugin: `index` is the parameter index an automation target takes, `value` and `display` are the library instance's saved setting, and the `at` columns, where present, are FL's display string with the knob set to that normalised value. `[landed x]` means the plugin stored x instead. Names containing MIDI CC, program, preset, bank, patch, browse or reserved were not swept.", "",
             "| file | plugin | kind | as FL names it | parameters | swept |", "|---|---|---|---|---|---|"]
    for r in index:
        f = library.param_file(r).name
        if r["rows"] is None:
            lines.append(f"| - | {r['name']} | {r['kind']} | not read | - | - |")
        else:
            lines.append(f"| `{f}` | {r['name']} | {r['kind']} | {r['live']} | {r['rows']} | {'yes' if r['swept'] else 'no'} |")
    (library.PARAMS / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return index


if __name__ == "__main__":
    idx = write()
    print(f"{sum(1 for r in idx if r['rows'] is not None)} of {len(idx)} plugins mapped into {library.PARAMS}")
    for r in idx:
        if r["rows"] is None:
            print("  not read:", r["name"])
    sys.exit(0)
